void main() {
    // Usando o operador módulo (%)
    // ENTRADA
    // Variável: numero
    int numero = 18;

    // PROCESSAMENTO
    // Variável: resto = o resto da divisão do número por 2
    int resto = numero % 2;

    // SAÍDA
    // Imprime o valor da variável resto
    System.out.println("O resto da divisão de " + numero + " por 2 é " + resto);
}