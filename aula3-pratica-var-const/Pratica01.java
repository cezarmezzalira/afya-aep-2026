void main() {
    System.out.println("Olá Mundo!");
    // Isso é um comentário
    /*
     * Este é um
     * comentário
     * de
     * várias linhas
     */

    // Variáveis

    // Tipo nome atribuição de valor e o valor
    String nome = "Coffee";

    // Mostra na tela o valor da variável nome
    System.out.println(nome);

    // Altera o valor da variável nome
    nome = "Milk";

    // Mostra na tela o valor da variável nome
    System.out.println(nome);

    // Constantes
    // final Tipo nome operador de atribuiçao e o valor
    
    // Constante do tipo ponto flutuante (float)
    // com menor precisão de casas decimais após a virgula
    final float PI = 3.141592f;

    // Mostra o valor da constante
    System.out.println(PI);

    // Constante do tipo ponto flutuante (float)
    // com maior precisão de casas decimais após a virgula
    final double cotacaoDolar = 5.39;

    // Mostra o valor da constante
    System.out.println(cotacaoDolar);

    // Não é possível modificar o valor da constante
    // cotacaoDolar, pois, ela é uma CONSTANTE!
    // cotacaoDolar = 5.40;

}