void main() {
    // Crie um vetor do tipo string para armazenar
    // uma lista de 3 nomes

    // Criação do vetor do tipo String, com 3 posições
    String[] nomes = new String[3];

    // Atribuindo valores
    nomes[0] = "Cezar";
    nomes[1] = "Caetano";
    nomes[2] = "Augusto";

    // Imprimindo valores
    System.out.println(nomes[0]);
    System.out.println(nomes[1]);
    System.out.println(nomes[2]);

    // Crie um vetor do tipo char para armazenar
    // uma lista com 4 letras
    char[] letras = { 'A', 'B', 'C', 'D' };

    letras[3] = 'd';

    System.out.println(letras[0]);
    System.out.println(letras[1]);
    System.out.println(letras[2]);
    System.out.println(letras[3]);
}