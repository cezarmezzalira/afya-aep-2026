void main() {
    // crie um vetor do tipo double com 4 posições
    // e atribua valor para as duas primeiras posições

    // Criação do vetor
    double[] notas = new double[4];

    // atribuindo valores as posições do vetor
    notas[0] = 70.0;
    notas[1] = 100.00;

    // acessando os valores das posições no vetor
    System.out.println(notas[0]);
    System.out.println(notas[1]);
    System.out.println(notas[2]);
    System.out.println(notas[3]);
}